    # ------------------------------------------------ F-PROMETHEE (fuzzy)
    fz = pb.config.get("fuzzy")
    if fz:
        L, M, U = fuzzy_matrix(pb.X, pb.criteria, A, fz["values"])

        def _f(v):
            return f"{v:.0f}" if abs(v) >= 100 else f"{v:g}"
        tfn = pd.DataFrame({cnames[j]: [f"({_f(L[i, j])}; {_f(M[i, j])}; {_f(U[i, j])})"
                                        if L[i, j] != U[i, j] else f"{_f(M[i, j])}"
                                        for i in range(n)] for j in range(m)},
                           index=pb.labels)
        tfn.index.name = "Alternative"
        tfn.to_csv(OUT / "fuzzy_decision_matrix.csv")
        ws = float(fz.get("weight_spread", 0.0))
        fr = fuzzy_promethee(L, M, U, pb.criteria, pb.weights, ws)
        ph = fr["phi"]
        fp = pd.DataFrame({"φ l": ph[:, 0], "φ m (= crisp φ)": ph[:, 1], "φ u": ph[:, 2],
                           "centroid (l+m+u)/3": fr["centroid"],
                           "F-PROMETHEE rank": ranks_from_scores(fr["centroid"])},
                          index=pb.labels)
        fp.index.name = "Alternative"
        fp = fp.sort_values("F-PROMETHEE rank")
        fp.to_csv(OUT / "fuzzy_promethee.csv")
        md += ["### 5.4 F-PROMETHEE – uncertain values as triangular fuzzy numbers\n",
               "Fuzzy decision matrix (l; m; u):\n", md_table(tfn), "",
               f"Weights are TFNs too: ({1 - ws:g}·w; w; {1 + ws:g}·w).\n",
               "Fuzzy net flows φ~ = (l; m; u) and ranking by the centroid:\n",
               md_table(fp, "{:+.3f}"), ""]

        fig, ax = plt.subplots(figsize=(7.8, 3.6))
        for i, a in enumerate(A):
            xs, ys = [ph[i, 0], ph[i, 1], ph[i, 2]], [0, 1, 0]
            ax.fill(xs, ys, color=color[a], alpha=0.15, lw=0)
            ax.plot(xs, ys, color=color[a], label=pb.labels[i])
            ax.plot([fr["centroid"][i]] * 2, [0, 0.06], color=color[a], lw=2.5)
        ax.axvline(0, color=AXIS, lw=0.8)
        ax.set_xlabel("fuzzy net flow φ~  (short tick = centroid)")
        ax.set_ylabel("membership")
        ax.set_ylim(0, 1.08)
        ax.legend(fontsize=8, loc="upper left", bbox_to_anchor=(1.01, 1))
        ax.set_title("F-PROMETHEE: fuzzy net flow of each printer (l; m; u)", loc="left")
        save(fig, "11_f_promethee.png")

    # --------------------------------------------- what-if: one performance
    wi = pb.config.get("what_if")
    if wi:
        ai, cj = A.index(wi["alternative"]), C.index(wi["criterion"])
        vals = np.linspace(wi["values_from"], wi["values_to"], 361)
        fl = []
        for v in vals:
            Xv = pb.X.copy()
            Xv[ai, cj] = v
            fl.append(promethee(Xv, pb.criteria, pb.weights).phi)
        fl = np.array(fl)
        win = fl.argmax(axis=1)
        # value where the alternative starts / stops being the winner
        is_best = win == ai
        switch = []
        for k in range(1, len(vals)):
            if is_best[k] != is_best[k - 1]:
                # interpolate where the alternative ties with the other leader
                other = win[k] if win[k] != ai else win[k - 1]
                d0 = fl[k - 1, ai] - fl[k - 1, other]
                d1 = fl[k, ai] - fl[k, other]
                switch.append(vals[k - 1] + (vals[k] - vals[k - 1]) * d0 / (d0 - d1))
        cur = pb.X[ai, cj]
        tab = []
        for v in sorted(set([cur, *[round(x) for x in np.linspace(wi["values_from"],
                                                                  wi["values_to"], 7)]])):
            Xv = pb.X.copy()
            Xv[ai, cj] = v
            rr = promethee(Xv, pb.criteria, pb.weights)
            tab.append({"value": v, **{A[i]: rr.phi[i] for i in range(n)},
                        "winner": pb.labels[int(np.argmax(rr.phi))],
                        f"rank of {A[ai]}": int(rr.ranks()[ai])})
        wi_df = pd.DataFrame(tab).set_index("value")
        wi_df.to_csv(OUT / "what_if.csv")
        md += [f"### 5.5 What-if: {wi.get('description', '')}\n",
               f"Varying `{cnames[cj]}` of {pb.labels[ai]} (current value {cur:g}), "
               "base weights.\n", md_table(wi_df, "{:+.3f}"), "",
               "Winner changes at: " + (", ".join(f"{x:.0f}" for x in switch)
                                        if switch else "never in this range") + "\n"]
        fig, ax = plt.subplots(figsize=(7.6, 3.6))
        for i, a in enumerate(A):
            ax.plot(vals, fl[:, i], color=color[a], label=pb.labels[i],
                    lw=2.6 if i == ai else 2)
        ax.axvline(cur, color=INK2, lw=1, ls="--")
        ax.text(cur, ax.get_ylim()[1], f" current {cur:g}", color=INK2, fontsize=8,
                va="top")
        for x in switch:
            ax.axvline(x, color=INK, lw=1, ls=":")
            ax.text(x, ax.get_ylim()[0], f" {x:.0f}", color=INK, fontsize=8,
                    va="bottom")
        ax.set_xlabel(f"{cnames[cj]} of {pb.labels[ai]}")
        ax.set_ylabel("net flow φ")
        ax.legend(fontsize=8, loc="upper left", bbox_to_anchor=(1.01, 1))
        ax.set_title(wi.get("description", "What-if"), loc="left")
        save(fig, "08_what_if.png")

    # ------------------------------------------ extension: efficiency measuring
    eff_cfg = pb.config.get("efficiency")
    if eff_cfg:
        cidx = [C.index(c) for c in eff_cfg["cost_criteria"]]
        bidx = [j for j in range(m) if j not in cidx]
        price = pb.X[:, cidx[0]]
        ben, cst = split_flows(res.phi_j, pb.weights, cidx)
        eff = efficient_set(ben, cst)
        # who dominates the inefficient ones
        dom_by = []
        for a in range(n):
            ds = [A[b] for b in range(n) if b != a and ben[b] >= ben[a] and cst[b] >= cst[a]
                  and (ben[b] > ben[a] or cst[b] > cst[a])]
            dom_by.append(", ".join(ds) if ds else "–")
        eff_df = pd.DataFrame({
            cnames[cidx[0]]: price.round().astype(int), "φ benefit (5 criteria)": ben,
            "φ cost (price)": cst, "efficient": np.where(eff, "yes", "no"),
            "dominated by": dom_by}, index=pb.labels)
        eff_df.index.name = "Alternative"
        eff_df = eff_df.sort_values(cnames[cidx[0]])
        eff_df.to_csv(OUT / "efficiency.csv")
        # steps along the frontier: extra money per extra benefit
        fr = sorted(np.where(eff)[0], key=lambda i: price[i])
        steps = []
        for i, k in zip(fr[:-1], fr[1:]):
            dp, db = price[k] - price[i], ben[k] - ben[i]
            steps.append({"from": pb.labels[i], "to": pb.labels[k], "extra price [EUR]": int(round(dp)),
                          "extra φ benefit": db, "EUR per +0.1 φ benefit": int(round(dp / db * 0.1))})
        step_df = pd.DataFrame(steps)
        if len(step_df):
            step_df = step_df.set_index("from")
        # reading the frontier: best printer (max benefit flow) for every budget
        budgets = np.arange(eff_cfg["budget_from"], eff_cfg["budget_to"] + 1, 1.0)
        choice = budget_sweep(ben, price, budgets)
        rows, prev = [], None
        for bgt, ch in zip(budgets, choice):
            if ch != prev:
                rows.append({"budget from [EUR]": bgt,
                             "best choice": pb.labels[ch] if ch >= 0 else "nothing affordable",
                             "φ benefit": ben[ch] if ch >= 0 else np.nan})
                prev = ch
        pv_df = pd.DataFrame(rows)
        pv_df["budget from [EUR]"] = pv_df["budget from [EUR]"].astype(int)
        pv_df = pv_df.set_index("budget from [EUR]")
        pv_df.to_csv(OUT / "budget_choice.csv")
        pv_task1, _ = best_within_budget(ben, price, 2500)
        pv_full, _ = best_within_budget(res.phi, price, 2500)
        # robustness: how often is each printer efficient under random weights
        acc = {f"efficient (±{int(s * 100)}%)": efficiency_acceptability(res.phi_j, pb.weights,
                                                                        cidx, spread=s)
               for s in (0.2, 0.5)}
        acc["efficient (any w)"] = efficiency_acceptability(res.phi_j, pb.weights, cidx,
                                                            mode="simplex")
        acc_df = pd.DataFrame(acc, index=pb.labels)
        acc_df.index.name = "Alternative"
        acc_df.to_csv(OUT / "efficiency_acceptability.csv")
        md += ["## 6. Extension – efficiency measuring\n",
               eff_cfg.get("description", ""), "",
               "### Cost and benefit flows, efficient set\n", md_table(eff_df, "{:+.3f}"), "",
               "### Steps along the efficient frontier\n",
               md_table(step_df, "{:+.3f}") if len(step_df) else "only one efficient printer", "",
               "### Reading the frontier: best printer (max φ benefit) for each budget\n",
               md_table(pv_df, "{:+.3f}"), "",
               f"With the Task 1 budget of 2500 EUR: maximising the benefit flow selects "
               f"**{pb.labels[pv_task1[0]]}**; maximising the full net flow (price as a "
               f"criterion) selects **{pb.labels[pv_full[0]]}**.\n",
               "### Robustness: share of random weight vectors for which a printer is "
               "efficient\n", md_table(acc_df, "{:.3f}"), ""]

        # fig: efficient frontier
        fig, ax = plt.subplots(figsize=(7.8, 4.4))
        order_fr = np.array(fr)
        ax.step(np.r_[price[order_fr], price.max() * 1.08], np.r_[ben[order_fr], ben[order_fr][-1]],
                where="post", color=AXIS, lw=1.5, zorder=1)
        for i, a in enumerate(A):
            ax.scatter(price[i], ben[i], s=130 if eff[i] else 90, color=color[a],
                       edgecolor=INK if eff[i] else "white", lw=2 if eff[i] else 1.5,
                       zorder=5, marker="o" if eff[i] else "X")
            tag = "efficient" if eff[i] else f"dominated by {dom_by[i]}"
            right = price[i] > np.median(price)
            ax.annotate(f"{pb.labels[i]}\n{tag}", (price[i], ben[i]),
                        textcoords="offset points", xytext=(-12 if right else 10, -6),
                        ha="right" if right else "left", va="top", fontsize=8.5, color=INK)
        ax.axhline(0, color=AXIS, lw=0.8)
        ax.set_xlabel(f"{cnames[cidx[0]]} (cost)")
        ax.set_ylabel("φ benefit (other criteria)")
        ax.set_xlim(price.min() * 0.85, price.max() * 1.15)
        pad = 0.25 * (ben.max() - ben.min())
        ax.set_ylim(ben.min() - pad, ben.max() + pad * 0.5)
        ax.set_title("Efficient frontier: input = price, output = φ benefit "
                     "(up-left is better)", loc="left")
        save(fig, "09_efficiency_frontier.png")

        # fig: best choice for each budget
        fig, ax = plt.subplots(figsize=(7.8, 1.9))
        ax.grid(axis="y", visible=False)
        ax.set_ylim(-0.45, 0.45)
        seg_start = 0
        for k in range(1, len(budgets) + 1):
            if k == len(budgets) or choice[k] != choice[seg_start]:
                ch = choice[seg_start]
                if ch >= 0:
                    ax.barh(0, budgets[k - 1] - budgets[seg_start] + 1, left=budgets[seg_start],
                            color=color[A[ch]], height=0.5, edgecolor="white", lw=2)
                    ax.text((budgets[seg_start] + budgets[k - 1]) / 2, 0, pb.alt_names[ch],
                            ha="center", va="center", fontsize=8.5,
                            color="white" if A[ch] != "A4" else INK)
                else:
                    ax.text((budgets[seg_start] + budgets[k - 1]) / 2, 0, "none",
                            ha="center", va="center", fontsize=8, color=INK2)
                seg_start = k
        ax.set_yticks([])
        ax.set_xlabel("budget [EUR]")
        ax.set_xlim(budgets[0], budgets[-1])
        ax.set_title("Best printer (max φ benefit) I can buy for a given budget",
                     loc="left")
        save(fig, "10_budget_choice.png")

    (OUT / "results.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


