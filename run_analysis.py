def main(path: str):
    OUT.mkdir(exist_ok=True)
    FIG.mkdir(exist_ok=True)
    pb = Problem.from_json(path)
    n, m = pb.X.shape
    A, C = pb.alt_ids, [c.id for c in pb.criteria]
    cnames = [c.name for c in pb.criteria]
    color = {a: SERIES[i % len(SERIES)] for i, a in enumerate(A)}
    md: list[str] = [f"# Results (auto-generated) – {pb.title}\n",
                     "_Generated by `run_analysis.py`. Interpretation: see `REPORT.md`._\n"]

    # ------------------------------------------------------------------ data
    perf = pd.DataFrame(pb.X, index=pb.labels, columns=cnames)
    perf.index.name = "Alternative"
    params = pd.DataFrame([{"criterion": c.name, "direction": c.direction,
                            "function": c.function, "q": c.q, "p": c.p, "s": c.s,
                            "weight": w} for c, w in zip(pb.criteria, pb.weights)],
                          index=C)
    params.index.name = "id"
    perf.to_csv(OUT / "performance_table.csv")
    params.to_csv(OUT / "criteria_parameters.csv")
    md += ["## 1. Input data\n", md_table(perf, "{:g}"), "",
           md_table(params, "{:g}"), ""]

    # ------------------------------------------------------- PROMETHEE I/II
    res = promethee(pb.X, pb.criteria, pb.weights)
    flows = pd.DataFrame({"phi+": res.phi_plus, "phi-": res.phi_minus,
                          "phi (net)": res.phi, "rank": res.ranks()}, index=pb.labels)
    flows.index.name = "Alternative"
    flows = flows.sort_values("rank")
    flows.to_csv(OUT / "promethee_flows.csv")
    pi_df = pd.DataFrame(res.pi, index=A, columns=A)
    pi_df.index.name = "pi(a,b)"
    pi_df.to_csv(OUT / "preference_index_matrix.csv")
    uni = pd.DataFrame(res.phi_j, index=pb.labels, columns=cnames)
    uni.index.name = "Alternative"
    uni.to_csv(OUT / "unicriterion_net_flows.csv")

    R1 = promethee_I(res)
    p1 = pd.DataFrame(R1, index=A, columns=A)
    p1.index.name = "a \\ b"
    p1.to_csv(OUT / "promethee_I_relations.csv")
    pairs_P, pairs_R = [], []
    for a in range(n):
        for b in range(n):
            if R1[a, b] == "P":
                pairs_P.append(f"{A[a]} P {A[b]}")
            if R1[a, b] == "R" and a < b:
                pairs_R.append(f"{A[a]} R {A[b]}")

    md += ["## 2. PROMETHEE II – complete ranking\n", md_table(flows), "",
           "### Aggregated preference indices pi(a,b)\n", md_table(pi_df, "{:.3f}"), "",
           "### Unicriterion net flows phi_j(a)\n", md_table(uni, "{:+.3f}"), "",
           "## 3. PROMETHEE I – partial preorder\n",
           "P = row outranks column, - = column outranks row, R = incomparable, "
           "I = indifferent\n", md_table(p1), "",
           f"Incomparable pairs: {', '.join(pairs_R) if pairs_R else 'none'}\n"]

    # fig: net flows
    order = res.ranking()
    fig, ax = plt.subplots(figsize=(7, 3.4))
    labels = [pb.labels[i] for i in order][::-1]
    vals = res.phi[order][::-1]
    ax.barh(labels, vals, color=[BLUE if v >= 0 else RED for v in vals], height=0.6)
    for y, v in enumerate(vals):
        ax.text(v + (0.006 if v >= 0 else -0.006), y, f"{v:+.3f}", va="center",
                ha="left" if v >= 0 else "right", color=INK, fontsize=9)
    ax.axvline(0, color=AXIS, lw=1)
    ax.set_xlabel("net flow φ")
    lim = np.abs(vals).max() * 1.3
    ax.set_xlim(-lim, lim)
    ax.grid(axis="y", visible=False)
    ax.set_title("PROMETHEE II complete ranking (base weights)", loc="left")
    save(fig, "01_net_flows.png")

    # fig: PROMETHEE I – phi+ / phi- scales
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    ax.grid(False)
    yl = res.phi_plus
    yr = 1 - res.phi_minus
    gap = 0.045 * (max(yl.max(), yr.max()) - min(yl.min(), yr.min()))
    ly, ry = spread_labels(yl, gap), spread_labels(yr, gap)
    for i, a in enumerate(A):
        ax.plot([0, 1], [yl[i], yr[i]], color=color[a], marker="o", ms=7,
                mec="white", mew=1.5)
        ax.text(-0.04, ly[i], f"{pb.labels[i]}  {res.phi_plus[i]:.3f}",
                ha="right", va="center", fontsize=8.5, color=INK)
        ax.text(1.04, ry[i], f"{res.phi_minus[i]:.3f}  {pb.labels[i]}",
                ha="left", va="center", fontsize=8.5, color=INK)
    ax.set_xlim(-0.9, 1.9)
    ax.set_xticks([0, 1], ["φ+ (higher = better)", "φ− (lower = better, axis inverted)"])
    ax.set_yticks([])
    for s in ("left", "bottom"):
        ax.spines[s].set_visible(False)
    ax.set_title("PROMETHEE I: crossing lines = incomparability", loc="left")
    save(fig, "02_promethee_I.png")

    # fig: unicriterion flow profile heatmap
    fig, ax = plt.subplots(figsize=(7.2, 3.4))
    ax.grid(False)
    im = ax.imshow(res.phi_j, cmap=DIVERGING, vmin=-1, vmax=1, aspect="auto")
    ax.set_xticks(range(m), [f"{c.id}\n{c.name}" for c in pb.criteria], fontsize=8)
    ax.set_yticks(range(n), pb.labels)
    for i in range(n):
        for j in range(m):
            ax.text(j, i, f"{res.phi_j[i, j]:+.2f}", ha="center", va="center",
                    color=INK if abs(res.phi_j[i, j]) < 0.6 else "white", fontsize=8.5)
    fig.colorbar(im, ax=ax, fraction=0.03, label="φj")
    ax.set_title("Unicriterion net flows – strengths (blue) and weaknesses (red)",
                 loc="left")
    save(fig, "03_unicriterion_profiles.png")

    # ----------------------------------------- ranking comparison / scenarios
    md.append("## 4. Comparison of rankings\n")
    scen = dict(pb.weight_scenarios) or {"Base": pb.weights}
    wsm_norm = pb.config.get("weighted_sum_normalisation", "ratio")
    rows_phi, rows_rank = {}, {}
    for name, w in scen.items():
        rr = promethee(pb.X, pb.criteria, w)
        rows_phi[f"PROMETHEE II – {name}"] = rr.phi
        rows_rank[f"PROMETHEE II – {name}"] = rr.ranks()
    for name, w in scen.items():
        ws = weighted_sum(pb.X, pb.criteria, w, wsm_norm)
        rows_phi[f"Weighted sum (P×W) – {name}"] = ws
        rows_rank[f"Weighted sum (P×W) – {name}"] = ranks_from_scores(ws)
    rank_df = pd.DataFrame(rows_rank, index=A).T
    rank_df.index.name = "Method / weights"
    score_df = pd.DataFrame(rows_phi, index=A).T
    score_df.index.name = "Method / weights"
    rank_df.to_csv(OUT / "ranking_comparison_ranks.csv")
    score_df.to_csv(OUT / "ranking_comparison_scores.csv")
    wtab = pd.DataFrame(scen, index=C).T
    wtab.index.name = "Scenario"
    base_key = next(iter(rows_rank))
    corr = pd.DataFrame({
        "Kendall τ vs base": [kendall_tau(rows_rank[base_key], r) for r in rows_rank.values()],
        "Spearman ρ vs base": [spearman_rho(rows_rank[base_key], r) for r in rows_rank.values()],
        "Best": [A[int(np.argmin(r))] for r in rows_rank.values()],
    }, index=rows_rank.keys())
    corr.index.name = "Method / weights"
    md += ["### Weight scenarios\n", md_table(wtab, "{:.3f}"), "",
           "### Ranks (1 = best)\n", md_table(rank_df, "{:d}"), "",
           f"### Scores (net flow φ for PROMETHEE, WSM score with `{wsm_norm}` "
           "normalisation for P×W)\n",
           md_table(score_df, "{:+.3f}"), "",
           f"### Rank correlation with `{base_key}`\n", md_table(corr, "{:.3f}"), ""]
    # PROMETHEE vs P×W within each scenario
    pw = pd.DataFrame({
        "Kendall τ (PROMETHEE vs P×W)": [
            kendall_tau(rows_rank[f"PROMETHEE II – {k}"], rows_rank[f"Weighted sum (P×W) – {k}"])
            for k in scen]}, index=list(scen))
    pw.index.name = "Scenario"
    md += [md_table(pw, "{:.3f}"), ""]

    # fig: rank comparison heatmap (ranks)
    fig, ax = plt.subplots(figsize=(7.6, 0.42 * len(rank_df) + 1.2))
    ax.grid(False)
    rv = rank_df.values.astype(float)
    ax.imshow(-rv, cmap=SEQUENTIAL, aspect="auto", vmin=-n - 1.5, vmax=0)
    for i in range(rv.shape[0]):
        for j in range(n):
            ax.text(j, i, int(rv[i, j]), ha="center", va="center",
                    color="white" if rv[i, j] <= 2 else INK, fontsize=9,
                    fontweight="bold" if rv[i, j] == 1 else "normal")
    ax.set_xticks(range(n), pb.labels, rotation=25, ha="right")
    ax.set_yticks(range(len(rank_df)), rank_df.index, fontsize=8.5)
    ax.axhline(len(scen) - 0.5, color="white", lw=4)
    ax.set_title("Rank of each alternative under each method and weight scenario "
                 "(1 = best)", loc="left")
    save(fig, "04_ranking_comparison.png")

    # ------------------------------------------------- sensitivity: weights
    md.append("## 5. Sensitivity analysis\n")
    stab = stability_intervals(res.phi_j, pb.weights)
    st_df = pd.DataFrame([{
        "criterion": cnames[s["j"]], "weight": s["weight"],
        "ranking stable from": s["rank_lo"], "ranking stable to": s["rank_hi"],
        "best stays best from": s["top_lo"], "best stays best to": s["top_hi"],
    } for s in stab], index=C)
    st_df.index.name = "id"
    st_df.to_csv(OUT / "weight_stability_intervals.csv")
    md += ["### 5.1 Weight stability intervals (exact)\n",
           "Other weights keep their proportions. `best` = "
           f"{pb.labels[stab[0]['best']]}.\n", md_table(st_df, "{:.3f}"), ""]

    # fig: OAT sweeps, small multiples
    cols = 3
    rows = int(np.ceil(m / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(11, 3.1 * rows), sharey=True)
    axes = np.atleast_1d(axes).ravel()
    for j in range(m):
        ax = axes[j]
        ts, fl = weight_sweep(res.phi_j, pb.weights, j)
        s = stab[j]
        ax.axvspan(s["rank_lo"], s["rank_hi"], color="#cde2fb", alpha=0.7, lw=0)
        for i, a in enumerate(A):
            ax.plot(ts, fl[:, i], color=color[a], label=pb.labels[i])
        ax.axvline(pb.weights[j], color=INK2, lw=1, ls="--")
        ax.set_title(f"{pb.criteria[j].id} {cnames[j]}", loc="left", fontsize=9.5)
        ax.set_xlabel(f"weight of {pb.criteria[j].id}")
        ax.axhline(0, color=AXIS, lw=0.8)
    for k in range(m, len(axes)):
        axes[k].axis("off")
    axes[0].set_ylabel("net flow φ")
    handles, lbls = axes[0].get_legend_handles_labels()
    if m % cols:
        fig.legend(handles, lbls, loc="lower right", bbox_to_anchor=(0.97, 0.12),
                   ncol=1, fontsize=8.5)
    else:
        fig.legend(handles, lbls, loc="upper center", bbox_to_anchor=(0.5, 0.0),
                   ncol=n, fontsize=8.5)
    fig.suptitle("Net flow vs weight of one criterion (dashed = base weight, "
                 "shaded = ranking unchanged)", x=0.01, ha="left", fontweight="bold")
    fig.tight_layout()
    save(fig, "05_weight_sweeps.png")

    # Monte Carlo
    acc_s, mr_s, _ = monte_carlo(res.phi_j, mode="simplex")
    acc_l, mr_l, _ = monte_carlo(res.phi_j, pb.weights, mode="local", spread=0.2)
    acc_l30, mr_l30, _ = monte_carlo(res.phi_j, pb.weights, mode="local", spread=0.5)
    rcols = [f"rank {r + 1}" for r in range(n)]
    acc_sdf = pd.DataFrame(acc_s, index=pb.labels, columns=rcols)
    acc_sdf["mean rank"] = mr_s
    acc_ldf = pd.DataFrame(acc_l, index=pb.labels, columns=rcols)
    acc_ldf["mean rank"] = mr_l
    acc_l5 = pd.DataFrame(acc_l30, index=pb.labels, columns=rcols)
    acc_l5["mean rank"] = mr_l30
    for d in (acc_sdf, acc_ldf, acc_l5):
        d.index.name = "Alternative"
    acc_sdf.to_csv(OUT / "rank_acceptability_simplex.csv")
    acc_ldf.to_csv(OUT / "rank_acceptability_local20.csv")
    acc_l5.to_csv(OUT / "rank_acceptability_local50.csv")
    md += ["### 5.2 Monte-Carlo rank acceptability (20 000 weight vectors)\n",
           "**(a) local: every base weight perturbed by ±20 %**\n",
           md_table(acc_ldf, "{:.3f}"), "",
           "**(b) local: every base weight perturbed by ±50 %**\n",
           md_table(acc_l5, "{:.3f}"), "",
           "**(c) global: weights uniformly random on the whole simplex**\n",
           md_table(acc_sdf, "{:.3f}"), ""]

    fig, axes = plt.subplots(1, 3, figsize=(13, 3.4), sharey=True)
    for ax, acc, ttl in zip(axes, (acc_l, acc_l30, acc_s),
                            ("±20 % around base weights", "±50 % around base weights",
                             "any weights (uniform simplex)")):
        ax.grid(False)
        ax.imshow(acc, cmap=SEQUENTIAL, vmin=0, vmax=1, aspect="auto")
        for i in range(n):
            for r in range(n):
                if acc[i, r] >= 0.005:
                    ax.text(r, i, f"{acc[i, r]:.0%}", ha="center", va="center",
                            fontsize=8, color="white" if acc[i, r] > 0.5 else INK)
        ax.set_xticks(range(n), [str(r + 1) for r in range(n)])
        ax.set_xlabel("rank position")
        ax.set_title(ttl, loc="left", fontsize=10)
    axes[0].set_yticks(range(n), pb.labels)
    fig.suptitle("Rank acceptability: share of random weight vectors giving each rank",
                 x=0.01, ha="left", fontweight="bold")
    fig.tight_layout()
    save(fig, "06_rank_acceptability.png")

    # ------------------------------------------- sensitivity: thresholds
    th = threshold_sensitivity(pb.X, pb.criteria, pb.weights)
    th_df = pd.DataFrame([{**{A[i]: int(r[i]) for i in range(n)},
                           "Kendall τ vs base": tau, "best": A[int(np.argmax(phi))]}
                          for _, phi, r, tau in th], index=[t[0] for t in th])
    th_df.index.name = "Preference-function variant"
    th_df.to_csv(OUT / "threshold_sensitivity.csv")
    md += ["### 5.3 Preference-function / threshold sensitivity (ranks)\n",
           md_table(th_df, "{:.3f}"), ""]

    # single-threshold sweeps for criteria having p
    sweep_c = [j for j, c in enumerate(pb.criteria) if c.function in
               ("linear", "v-shape", "level")]
    if sweep_c:
        ncol = min(3, len(sweep_c))
        nrow = int(np.ceil(len(sweep_c) / ncol))
        fig, axes = plt.subplots(nrow, ncol, figsize=(3.9 * ncol + 1.6, 3.0 * nrow),
                                 sharey=True, squeeze=False)
        axes = axes.ravel()
        for k in range(len(sweep_c), len(axes)):
            axes[k].axis("off")
        for ax, j in zip(axes, sweep_c):
            c = pb.criteria[j]
            vals = np.linspace(max(c.q, 1e-6) if c.function != "v-shape" else 1e-6,
                               3 * c.p, 60)
            fl = single_threshold_sweep(pb.X, pb.criteria, pb.weights, j, "p", vals)
            for i, a in enumerate(A):
                ax.plot(vals, fl[:, i], color=color[a], label=pb.labels[i])
            ax.axvline(c.p, color=INK2, lw=1, ls="--")
            ax.set_title(f"{c.id}: preference threshold p", loc="left", fontsize=9.5)
            ax.set_xlabel(f"p ({c.name})")
        for k in range(0, len(axes), ncol):
            axes[k].set_ylabel("net flow φ")
        axes[ncol - 1].legend(fontsize=7.5, loc="upper left", bbox_to_anchor=(1.02, 1.0))
        fig.suptitle("Net flows vs preference threshold p (dashed = value used)",
                     x=0.01, ha="left", fontweight="bold")
        fig.tight_layout()
        save(fig, "07_threshold_sweeps.png")

    # --------------------------------------------- what-if: one performance
    wi = pb.config.get("what_if")
    if wi:
        ai, cj = A.index(wi["alternative"]), C.index(wi["criterion"])
        vals = np.linspace(wi["values_from"], wi["values_to"], 361)
        fl = []
        for v in vals:
            Xv = pb.X.copy()
            Xv[ai, cj] = v
            fl.append(promethee(Xv, pb.criteria, pb.weights).phi)
        fl = np.array(fl)
        win = fl.argmax(axis=1)
        # value where the alternative starts / stops being the winner
        is_best = win == ai
        switch = []
        for k in range(1, len(vals)):
            if is_best[k] != is_best[k - 1]:
                # interpolate where the alternative ties with the other leader
                other = win[k] if win[k] != ai else win[k - 1]
                d0 = fl[k - 1, ai] - fl[k - 1, other]
                d1 = fl[k, ai] - fl[k, other]
                switch.append(vals[k - 1] + (vals[k] - vals[k - 1]) * d0 / (d0 - d1))
        cur = pb.X[ai, cj]
        tab = []
        for v in sorted(set([cur, *[round(x) for x in np.linspace(wi["values_from"],
                                                                  wi["values_to"], 7)]])):
            Xv = pb.X.copy()
            Xv[ai, cj] = v
            rr = promethee(Xv, pb.criteria, pb.weights)
            tab.append({"value": v, **{A[i]: rr.phi[i] for i in range(n)},
                        "winner": pb.labels[int(np.argmax(rr.phi))],
                        f"rank of {A[ai]}": int(rr.ranks()[ai])})
        wi_df = pd.DataFrame(tab).set_index("value")
        wi_df.to_csv(OUT / "what_if.csv")
        md += [f"### 5.4 What-if: {wi.get('description', '')}\n",
               f"Varying `{cnames[cj]}` of {pb.labels[ai]} (current value {cur:g}), "
               "base weights.\n", md_table(wi_df, "{:+.3f}"), "",
               "Winner changes at: " + (", ".join(f"{x:.0f}" for x in switch)
                                        if switch else "never in this range") + "\n"]
        fig, ax = plt.subplots(figsize=(7.6, 3.6))
        for i, a in enumerate(A):
            ax.plot(vals, fl[:, i], color=color[a], label=pb.labels[i],
                    lw=2.6 if i == ai else 2)
        ax.axvline(cur, color=INK2, lw=1, ls="--")
        ax.text(cur, ax.get_ylim()[1], f" current {cur:g}", color=INK2, fontsize=8,
                va="top")
        for x in switch:
            ax.axvline(x, color=INK, lw=1, ls=":")
            ax.text(x, ax.get_ylim()[0], f" {x:.0f}", color=INK, fontsize=8,
                    va="bottom")
        ax.set_xlabel(f"{cnames[cj]} of {pb.labels[ai]}")
        ax.set_ylabel("net flow φ")
        ax.legend(fontsize=8, loc="upper left", bbox_to_anchor=(1.01, 1))
        ax.set_title(wi.get("description", "What-if"), loc="left")
        save(fig, "08_what_if.png")

    # ------------------------------------------------ extension: FlowSort
    srt = pb.config.get("sort")
    if srt:
        classes = srt["classes"]
        K = len(classes)
        R = np.array(list(srt["profiles"].values()), float)
