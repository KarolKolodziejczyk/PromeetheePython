def md_table(df: pd.DataFrame, floatfmt: str = "{:.4f}") -> str:
    cols = [str(df.index.name or "")] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in zip(df.index, df.astype(object).itertuples(index=False)):
        cells = [str(idx)]
        for col, v in zip(df.columns, row):
            if pd.api.types.is_integer_dtype(df[col].dtype):
                cells.append(str(int(v)))
            elif isinstance(v, (float, np.floating)):
                cells.append("–" if np.isnan(v) else floatfmt.format(v))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def spread_labels(y, min_gap):
    """Return label positions with at least ``min_gap`` between neighbours."""
    y = np.asarray(y, float)
    order = np.argsort(y)
    pos = y[order].copy()
    for k in range(1, len(pos)):
        pos[k] = max(pos[k], pos[k - 1] + min_gap)
    shift = (pos - y[order]).mean()
    pos -= shift / 2
    out = np.empty_like(pos)
    out[order] = pos
    return out


